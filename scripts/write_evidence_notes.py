#!/usr/bin/env python3
"""Render docs/evidence.md from evidence/studionet_deployment.json.

The markdown is generated, never hand written, so the numbers in the README and in
the review notes cannot drift away from what the chain actually returned.

    .venv/bin/python scripts/write_evidence_notes.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVIDENCE = ROOT / "evidence" / "studionet_deployment.json"
OUT = ROOT / "docs" / "evidence.md"


def gen(value: str | int) -> str:
    return "%.6f" % (int(value) / 10 ** 18)


def main() -> int:
    if not EVIDENCE.exists():
        print("no evidence file yet, run scripts/deploy_studionet.py first")
        return 2
    data = json.loads(EVIDENCE.read_text(encoding="utf-8"))
    state = data["onchain_state"]
    identity = data["sha256_identity"]
    payout = data.get("payout_proof", {})
    lines: list[str] = []
    add = lines.append

    add("# ProphetSyndicate studionet evidence")
    add("")
    add("Generated by `scripts/write_evidence_notes.py` from `evidence/studionet_deployment.json`.")
    add("")
    add("| Item | Value |")
    add("|---|---|")
    add("| Network | %s, chain id %d |" % (data["network"], data["chain_id"]))
    add("| RPC | %s |" % data["rpc_url"])
    add("| Intelligent contract | `%s` |" % data["contract_address"])
    add("| Deployer | `%s` |" % data["deployer"])
    add("| Deployed at | %s |" % data.get("deployed_at"))
    add("| Runner pin | `%s` |" % data["runner_pin"])
    add("| Linked ProphetGrid | `%s` |" % data["linked_prophet_grid_address"])
    add("| Macro volatility feed | %s |" % data["feeds"]["macro_volatility"])
    add("| ProphetGrid depth feed | %s |" % data["feeds"]["prophet_grid_depth"])
    add("| Windows (s) | subscribe %d, challenge %d, audit timeout %d |" % (
        data["windows"]["subscription_seconds"], data["windows"]["challenge_seconds"],
        data["windows"]["audit_timeout_seconds"]))
    add("| Explorer | %s |" % data["explorer"])
    add("| Transactions | %d, all FINALIZED with leader execution SUCCESS |" % len(data["transactions"]))
    add("| Ledger custody | %s GEN |" % gen(state["native_custody_balance"]))
    add("| Chain balance of the vault | %s GEN |" % gen(data["native_balance_of_vault_wei"]))
    add("| Vault account balance read by the contract | %s GEN |" % gen(state.get("vm_account_balance_wei", -1)))
    add("")
    add("## On chain invariants")
    add("")
    add("```json")
    add(json.dumps({"ok": state["ok"], "checks": state["checks"], "partition": state["partition"]}, indent=2))
    add("```")
    add("")
    add("reserved principal liability %s GEN, unfunded senior floor %s GEN, epochs %s, LPs %s" % (
        gen(state["reserved_liability_wei"]), gen(state["unfunded_floor_wei"]), state["epoch_count"], state.get("lp_count", "n/a")))
    add("")
    add("## Routing epochs")
    add("")
    add("| Epoch | Status | Band | Volatility bps | Tail risk bps | Routed wei | Shield wei | Senior bps | Junior bps | Floor wei |")
    add("|---|---|---|---|---|---|---|---|---|---|")
    for row in state["epochs"]:
        add("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            row["epoch_id"], row["status"], row["routing_band"] or "none",
            row["quantized_volatility_baseline_bps"], row["quantized_tail_risk_bps"],
            gen(row["derived_active_deployment_amount"]), gen(row["derived_senior_reserve_buffer"]),
            row["derived_senior_yield_bps"], row["derived_junior_yield_bps"], gen(row["senior_floor_wei"]))
        )
    add("")
    cc = data.get("cross_contract_proof", {})
    proofs = cc.get("positions_by_epoch", {})
    if proofs:
        add("## Real cross contract deployment and reconciliation")
        add("")
        add("| Epoch | Live market | Routed GEN | Reconciled | Grid recorded this desk |")
        add("|---|---|---|---|---|")
        for eid in sorted(proofs, key=lambda x: int(x)):
            p = proofs[eid]
            view = p.get("reconciled_view") or p.get("syndicate_view") or {}
            portfolio = p.get("grid_trader_portfolio") or {}
            held = any(str(m.get("market_id")) == str(p.get("market_id")) for m in portfolio.get("positions", []))
            add("| %s | %s | %s | %s | %s |" % (
                eid, p.get("market_id"), gen(p.get("routed_wei", 0)),
                "yes" if view.get("reconciled") else "no", "yes" if held else "no"))
        add("")
        add("active deployed to ProphetGrid %s GEN, reconciled proceeds total %s GEN, total custody assets %s GEN, chain balance equals native custody: %s" % (
            gen(cc.get("active_deployed_to_prophet_grid_wei", 0)), gen(cc.get("reconciled_proceeds_total_wei", 0)),
            gen(cc.get("total_custody_assets_wei", 0)), cc.get("chain_balance_equals_native_custody")))
        add("")
        add(cc.get("reading", ""))
        add("")
    add("## Transactions")
    add("")
    add("| Function | Account | Status | Result | Leader execution | Agree / total | Hash |")
    add("|---|---|---|---|---|---|---|")
    for tx in data["transactions"]:
        if not tx.get("function"):
            continue
        add("| %s | %s | %s | %s | %s | %s / %s | `%s` |" % (
            tx["function"], str(tx.get("account", ""))[:10], tx["status"], tx["result"], tx["execution"],
            tx.get("votes_agree", 0), tx.get("votes_total", 0), str(tx["tx_hash"])[:20]))
    add("")
    add("## Claim rail")
    add("")
    add("Rejected value, settled principal and yield all leave through the same rail. Finalized payout transactions:")
    add("")
    for tx in payout.get("payout_transactions", []):
        add("* `%s` by `%s` (`%s`) reported `%s` / `%s`" % (
            str(tx["tx_hash"])[:24], str(tx["account"])[:10], tx["function"], tx["status"], tx["execution"]))
    add("")
    add("Residual ledger custody %s GEN equals the chain account balance of the vault: %s. Claimable still inside the vault: %s GEN." % (
        gen(payout.get("residual_custody_wei", 0)), payout.get("custody_equals_chain_balance"),
        gen(payout.get("claimable_still_in_vault_wei", 0))))
    add("")
    add(payout.get("reading", ""))
    add("")
    add("## Soft fail proof from the run")
    add("")
    add("```json")
    add(json.dumps(data.get("refund_proof", {}), indent=2))
    add("```")
    add("")
    add("## Four way sha256 identity")
    add("")
    add("```json")
    add(json.dumps(identity, indent=2))
    add("```")
    add("")
    add("## Verification method and honest limits")
    add("")
    add(data["verification_method"])
    add("")
    add("* Direct mode tests execute the leader path only. The votes column above is the live")
    add("  validator agreement record for each consensus call.")
    add("* `eth_getBalance` for externally owned accounts lagged on studionet during the run, so")
    add("  per wallet deltas are not claimed; the vault account balance is checked instead.")
    add("* Failures observed during the run: %d." % len(data.get("failures_observed", [])))
    add("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s (%d lines)" % (OUT.relative_to(ROOT), len(lines)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
